-- Q6. Employees with their department: the other schema is named explicitly (owner.table).
SELECT E.EMPNO, E.ENAME, E.JOB, E.SAL, D.DEPTNO, D.DNAME, D.LOC
FROM EMP E JOIN USER2.DEPT D ON E.DEPTNO = D.DEPTNO
ORDER BY D.DEPTNO, E.ENAME;

-- Q7, child side.
-- (a) department 99 does not exist: expected ORA-02291 (parent key not found)
INSERT INTO EMP (EMPNO, ENAME, JOB, SAL, DEPTNO) VALUES (8000, 'TEST', 'CLERK', 1000, 99);
-- (b) moving an employee to a missing department: expected ORA-02291
UPDATE EMP SET DEPTNO = 99 WHERE EMPNO = 7369;
-- (c) existing department 40: accepted, then cancelled
INSERT INTO EMP (EMPNO, ENAME, JOB, SAL, DEPTNO) VALUES (8000, 'TEST', 'CLERK', 1000, 40);
ROLLBACK;
-- (d) NULL is accepted: a foreign key only checks values that are filled in
INSERT INTO EMP (EMPNO, ENAME, JOB, SAL, DEPTNO) VALUES (8001, 'SANSDEPT', 'CLERK', 1000, NULL);
ROLLBACK;

-- Q8. Private synonym: USER1 writes DEPT instead of USER2.DEPT.
