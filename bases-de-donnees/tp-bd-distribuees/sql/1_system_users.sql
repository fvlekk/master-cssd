-- Run as SYSTEM in FREEPDB1.
-- Q1. Create USER1 (owner of EMP) and USER2 (owner of DEPT). Dropped first so the TP can be replayed;
-- USER1 goes first because its foreign key depends on USER2.DEPT.
DROP USER IF EXISTS USER1 CASCADE;
DROP USER IF EXISTS USER2 CASCADE;

CREATE USER USER1 IDENTIFIED BY user1 DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS;
CREATE USER USER2 IDENTIFIED BY user2 DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS;

GRANT CREATE SESSION, CREATE TABLE, CREATE SYNONYM TO USER1;
GRANT CREATE SESSION, CREATE TABLE TO USER2;

SELECT USERNAME, DEFAULT_TABLESPACE FROM DBA_USERS WHERE USERNAME IN ('USER1', 'USER2') ORDER BY 1;
EXIT;
